BattingEntry _bat(
  String name,
  String dismissal,
  int runs,
  int balls, {
  int fours = 0,
  int sixes = 0,
}) =>
    BattingEntry(
      name: name,
      dismissal: dismissal,
      runs: runs,
      balls: balls,
      fours: fours,
      sixes: sixes,
    );

BowlingEntry _bowl(
  String name,
  String overs,
  int maidens,
  int runs,
  int wickets,
) =>
    BowlingEntry(
      name: name,
      overs: overs,
      maidens: maidens,
      runs: runs,
      wickets: wickets,
    );

